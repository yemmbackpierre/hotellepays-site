export { UNSPECIFIED_KEYWORDS, LOW_KEYWORDS, MEDIUM_KEYWORDS, HIGH_KEYWORDS };

// =======================
// Helper d’adaptation
// =======================

const adaptKeywords = (
    keywords: Keyword[],
    competition: CompetitionLevel
): KeywordEntry[] => {
    return keywords.map((k) => ({
        ...k,
        competition,
    }));
};

// =======================
// Fusion globale
// =======================

const ALL_KEYWORDS: KeywordEntry[] = [
    ...adaptKeywords(HIGH_KEYWORDS, "HIGH"),
    ...adaptKeywords(MEDIUM_KEYWORDS, "MEDIUM"),
    ...adaptKeywords(LOW_KEYWORDS, "LOW"),
    ...adaptKeywords(UNSPECIFIED_KEYWORDS, "UNSPECIFIED"),
];

// =======================
// Extraction depuis un texte
// =======================

export const extractKeywords = (text: string): KeywordEntry[] => {
    if (!text) return [];

    const normalizedText = text.toLowerCase();

    return ALL_KEYWORDS.filter((item) =>
        normalizedText.includes(item.keyword.toLowerCase())
    );
};

